# ---------- reading paddock.js ----------
def read_paddock(path="paddock.js"):
    out, on = [], False
    for line in open(path, encoding="utf-8").read().splitlines():
        if re.match(r"\s*const\s+PADDOCK\s*=", line): on = True; continue
        if on and re.match(r"\s*\{id:", line): out.append(parse_obj(line))
        elif on and line.strip().startswith("];"): on = False
    return out


def town(x): return ", ".join(v for v in (x.get("city"), x.get("state")) if v)
def where(x): return town(x) or ("Southern California" if x.get("region") == "Southern California" else STATES.get(x.get("state"), x.get("state", "")))
def out_rel(x): return "sponsored noopener" if (x.get("sponsored") or x.get("affiliate")) else "noopener"


def json_ld(x, page):
    typ = CAT_INFO[x["category"]][2]
    o = {"@type": typ, "@id": page + "#place", "name": x["name"], "url": x.get("url") or page, "description": x.get("blurb", "")}
    if x.get("city") or x.get("address"):
        a = {"@type": "PostalAddress", "addressCountry": "US"}
        if x.get("address"): a["streetAddress"] = x["address"]
        if x.get("city"): a["addressLocality"] = x["city"]
        if x.get("state"): a["addressRegion"] = x["state"]
        o["address"] = a
    if x.get("phone"): o["telephone"] = x["phone"]
    if isinstance(x.get("lat"), (int, float)): o["geo"] = {"@type": "GeoCoordinates", "latitude": x["lat"], "longitude": x["lng"]}
    ig = ig_url(x.get("instagram"))
    if ig: o["sameAs"] = [ig]
    crumbs = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "The Paddock", "item": SITE + "/paddock/"},
        {"@type": "ListItem", "position": 2, "name": x["category"], "item": f"{SITE}/paddock/{CAT_INFO[x['category']][0]}/"},
        {"@type": "ListItem", "position": 3, "name": x["name"], "item": page}]}
    return json.dumps({"@context": "https://schema.org", "@graph": [o, crumbs]}, ensure_ascii=False).replace("</", "<\\/")


