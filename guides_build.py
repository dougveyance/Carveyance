def stats_html(spec):
    if not spec:
        return ""
    cells = ""
    for part in spec.split("|"):
        if "=" not in part:
            continue
        val, lab = [x.strip() for x in part.split("=", 1)]
        sub = ""
        m = re.match(r"^(.*?)\s*\((.+)\)$", lab)
        if m:
            lab, sub = m.group(1), m.group(2)
        num = re.match(r"^([\d.,$]+)\s*(.*)$", val)
        v = f'{esc(num.group(1))}<small>{esc(num.group(2))}</small>' if num and num.group(2) else esc(val)
        subx = '<div class="s">' + esc(sub) + "</div>" if sub else ""
        cells += f'<div class="gs"><div class="v">{v}</div><div class="l">{esc(lab)}</div>{subx}</div>'
    return f'<div class="gstats">{cells}</div>'


