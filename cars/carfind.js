/* The Car Index quick finder. Static file: loaded by every car, family and
   compare page via the findbar. The slim index (cars/search-index.js) is
   generated by cars_build.py and loaded lazily on first focus. */
(function () {
  var input = document.getElementById('carfind');
  var box = document.getElementById('carfind-results');
  if (!input || !box) return;

  var loaded = false, loading = false, active = -1, rows = [];

  function loadIndex(cb) {
    if (loaded) return cb();
    if (loading) return;
    loading = true;
    var s = document.createElement('script');
    s.src = '/cars/search-index.js';
    s.onload = function () { loaded = true; loading = false; cb(); };
    s.onerror = function () { loading = false; };
    document.head.appendChild(s);
  }

  function norm(t) { return (t || '').toLowerCase().replace(/[–—]/g, '-'); }

  function rank(c, q, toks) {
    var n = norm(c.n), a = norm(c.a), m = norm(c.m), hay = n + ' ' + a + ' ' + m + ' ' + norm(c.y);
    for (var i = 0; i < toks.length; i++) if (hay.indexOf(toks[i]) === -1) return -1;
    if (n.indexOf(q) === 0) return 0;
    if (n.indexOf(' ' + q) !== -1 || n.indexOf(q) !== -1) return 1;
    if (a.indexOf(q) !== -1) return 2;
    return 3;
  }

  function render(list) {
    rows = list; active = -1;
    if (!list.length) { box.hidden = true; box.innerHTML = ''; return; }
    box.innerHTML = list.map(function (c, i) {
      return '<a class="fb-row" data-i="' + i + '" href="/cars/' + c.i + '/">' +
        '<span class="fb-n">' + c.n.replace(/</g, '&lt;') + '</span>' +
        '<span class="fb-y">' + (c.y || '').replace(/</g, '&lt;') + '</span></a>';
    }).join('');
    box.hidden = false;
  }

  function search() {
    var q = norm(input.value).trim();
    if (q.length < 2) { render([]); return; }
    var toks = q.split(/\s+/);
    var hits = [];
    for (var i = 0; i < CAR_SEARCH.length; i++) {
      var r = rank(CAR_SEARCH[i], q, toks);
      if (r !== -1) hits.push([r, CAR_SEARCH[i]]);
    }
    hits.sort(function (x, y) { return x[0] - y[0] || (y[1].s || 0) - (x[1].s || 0) || x[1].n.length - y[1].n.length; });
    render(hits.slice(0, 8).map(function (h) { return h[1]; }));
  }

  function mark() {
    var kids = box.children;
    for (var i = 0; i < kids.length; i++) kids[i].classList.toggle('on', i === active);
    if (active >= 0 && kids[active]) kids[active].scrollIntoView({ block: 'nearest' });
  }

  input.addEventListener('focus', function () { loadIndex(search); });
  input.addEventListener('input', function () { loadIndex(search); if (loaded) search(); });
  input.addEventListener('keydown', function (e) {
    if (box.hidden) return;
    if (e.key === 'ArrowDown') { e.preventDefault(); active = Math.min(active + 1, rows.length - 1); mark(); }
    else if (e.key === 'ArrowUp') { e.preventDefault(); active = Math.max(active - 1, 0); mark(); }
    else if (e.key === 'Enter' && active >= 0) { e.preventDefault(); location.href = '/cars/' + rows[active].i + '/'; }
    else if (e.key === 'Escape') { render([]); input.blur(); }
  });
  document.addEventListener('click', function (e) {
    if (!box.contains(e.target) && e.target !== input) render([]);
  });
})();
