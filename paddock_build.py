def static_list(items):
    """the plain list on paddock/index.html (replaced by the live grid when JavaScript runs)"""
    out = []
    for cat in CAT_INFO:
        rows = sorted([x for x in items if x["category"] == cat], key=lambda x: (x["region"] != LA_REGION, x["name"].lower()))
        if not rows: continue
        out.append(f'<h3><a href="/paddock/{CAT_INFO[cat][0]}/">{esc(cat)}</a></h3><ul>' + "".join(
            f'<li><a href="/paddock/{x["id"]}/">{esc(x["name"])}</a> — {esc(where(x))}</li>' for x in rows) + "</ul>")
    return "\n".join(out)


def nearest(x, pool, n, maxmi):
    if not isinstance(x.get("lat"), (int, float)): return []
    out = []
    for y in pool:
        if y is x or y.get("id") == x.get("id") or not isinstance(y.get("lat"), (int, float)): continue
        mi = miles(x["lat"], x["lng"], y["lat"], y["lng"])
        if mi <= maxmi: out.append(dict(y, _mi=mi))
    return sorted(out, key=lambda y: y["_mi"])[:n]


def main():
    if not os.path.exists("paddock.js"):
        sys.exit("Run this from the top level of the repo (the folder holding paddock.js).")
    items = read_paddock()
    bad = [x["id"] for x in items if x.get("category") not in CAT_INFO]
    if bad: sys.exit("Unknown category on: " + ", ".join(bad))
    reserved = {v[0] for v in CAT_INFO.values()}
    clash = [x["id"] for x in items if x["id"] in reserved]
    if clash: sys.exit("These ids clash with a category page name: " + ", ".join(clash))

    # upcoming events, for "Car events nearby"
    evs = []
    if os.path.exists("events.js"):
        events, meets = read_events()
        for e in events:
            if e.get("end", e.get("start", "")) >= TODAY.isoformat() and e.get("status") not in ("canceled", "postponed", "expected"):
                s = e["start"]; evs.append(dict(e, _when=fmt_day(max(TODAY, __import__("datetime").date.fromisoformat(s)))))
        for m in meets:
            if m.get("status") in ("canceled", "postponed"): continue
            occ = occurrences(m, 1)
            if occ: evs.append(dict(m, _when=m.get("schedule", "") ))

    os.makedirs("paddock", exist_ok=True)
    want = set()
    for x in items:
        near_p = nearest(x, items, 5, 40)
        near_e = nearest(x, evs, 5, 25)
        folder = os.path.join("paddock", x["id"]); want.add(x["id"])
        os.makedirs(folder, exist_ok=True)
        with open(os.path.join(folder, "index.html"), "w", encoding="utf-8") as f: f.write(listing_page(x, near_p, near_e))
    ncat = 0
    for cat in CAT_INFO:
        rows = [x for x in items if x["category"] == cat]
        if not rows: continue
        folder = os.path.join("paddock", CAT_INFO[cat][0]); want.add(CAT_INFO[cat][0]); ncat += 1
        os.makedirs(folder, exist_ok=True)
        with open(os.path.join(folder, "index.html"), "w", encoding="utf-8") as f: f.write(category_page(cat, rows))

    removed = 0
    for name in os.listdir("paddock"):
        p = os.path.join("paddock", name, "index.html")
        if name in want or not os.path.isfile(p): continue
        with open(p, encoding="utf-8") as f: top = f.read(400)
        if MARK in top: shutil.rmtree(os.path.join("paddock", name)); removed += 1

    hub = os.path.join("paddock", "index.html")
    if os.path.exists(hub):
        src = open(hub, encoding="utf-8").read()
        if LIST_START in src and LIST_END in src:
            a, b = src.index(LIST_START) + len(LIST_START), src.index(LIST_END)
            src = src[:a] + "\n" + static_list(items) + "\n" + src[b:]
            open(hub, "w", encoding="utf-8").write(src)
    print(f"paddock pages: {len(items)} listings, {ncat} categories, {removed} removed")
    print("Next: python3 seo_inject.py (adds The Paddock pages to sitemap.xml)")


if __name__ == "__main__":
    main()
