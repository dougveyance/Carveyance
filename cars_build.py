def static_list(cars):
    by_make = {}
    for c in cars:
        by_make.setdefault(c["make"], []).append(c)
    out = []
    for make in sorted(by_make, key=str.lower):
        items = "".join(f'<li><a href="/cars/{esc(c["id"])}/">{esc(c["name"])}</a> — {esc(c.get("years", ""))}</li>'
                        for c in sorted(by_make[make], key=lambda x: (x.get("start") or 0, x["name"])))
        out.append(f'<h3><a href="/cars/?make={urllib.parse.quote(make)}">{esc(make)}</a></h3><ul>{items}</ul>')
    return "\n".join(out)


def link_articles(cars, arts):
    """add or refresh the 'Rate the cars in this story' strip in each article"""
    feat = {}
    for c in cars:
        for s in list(c.get("articles", [])) + list(c.get("_also", [])):
            feat.setdefault(s, []).append(c)
    done = 0
    for slug, lst in feat.items():
        path = os.path.join("articles", slug, "index.html")
        if not os.path.exists(path):
            continue
        page = open(path, encoding="utf-8").read()
        primary = [c for c in lst if slug in c.get("articles", [])]
        others = [c for c in lst if c not in primary]
        lst = (primary + others)[:6]
        links = "".join(
            f'<a href="/cars/{esc(c["id"])}/" style="display:inline-flex;align-items:center;gap:8px;margin:0 8px 8px 0;padding:9px 14px;border:1px solid rgba(255,255,255,.25);border-radius:999px;color:#fff;text-decoration:none;font-size:15px">'
            f'<span style="color:#e05c2a">&#9679;</span>{esc(c["name"])}</a>' for c in lst)
        block = (f'{ART_START}\n<aside class="cv-index" aria-label="In the Car Index" style="max-width:720px;margin:48px auto 8px;padding:26px 30px;background:#141820;color:#fff;border-radius:3px;font-family:\'DM Sans\',Arial,sans-serif">'
                 '<p style="margin:0 0 6px;font-size:12px;font-weight:600;letter-spacing:.16em;text-transform:uppercase;color:#4E8DB5">The Car Index</p>'
                 '<p style="margin:0 0 16px;font-size:20px;line-height:1.35">How many steering wheels out of 10 would you give '
                 + ("it" if len(lst) == 1 else "them") + '? Rate the cars in this story.</p>'
                 f'<div>{links}</div></aside>\n{ART_END}')
        if ART_START in page and ART_END in page:
            new = re.sub(re.escape(ART_START) + r".*?" + re.escape(ART_END), lambda m: block, page, flags=re.S)
        elif "<!-- carveyance-subscribe -->" in page:
            new = page.replace("<!-- carveyance-subscribe -->", block + "\n<!-- carveyance-subscribe -->", 1)
        elif "</body>" in page:
            new = page.replace("</body>", block + "\n</body>", 1)
        else:
            continue
        if new != page:
            open(path, "w", encoding="utf-8").write(new)
            done += 1
    print(f"Articles given a Car Index strip (or refreshed): {done}")


def main():
    if not os.path.exists("cars.js") or not os.path.exists("articles.js"):
        sys.exit("Run this from the top level of the repo (the folder holding cars.js and articles.js).")
    args = sys.argv[1:]
    cars = read_cars()
    arts = read_articles()
    if "--download-photos" in args:
        download_photos(cars)

    by_id = {c["id"]: c for c in cars}
    # which other stories mention each car, by the vehicle names tagged in articles.js
    for c in cars:
        names = {n.lower() for n in (c.get("match") or [])}
        c["_also"] = [s for s, a in arts.items()
                      if s not in c.get("articles", []) and names & {v.lower() for v in a["vehicles"]}]
        missing = [s for s in c.get("articles", []) if s not in arts]
        if missing:
            print(f"  note: {c['id']} lists articles not in articles.js: {', '.join(missing)}")
    photos = {c["id"]: photo_urls(c) for c in cars}

    # the data the /cars/ page reads
    data = []
    for c in cars:
        dates = [arts[s]["date"] for s in c.get("articles", []) + c["_also"] if s in arts and arts[s].get("date")]
        ph = photos[c["id"]]
        data.append({"id": c["id"], "name": c["name"], "aka": c.get("aka", []), "make": c["make"], "maker": c.get("maker", ""),
                     "years": c.get("years", ""), "start": c.get("start"), "body": c.get("body", ""), "engine": c.get("engine", ""),
                     "country": c.get("country", ""), "quick": c.get("quick", ""), "articles": c.get("articles", []) + c["_also"],
                     "latest": max(dates) if dates else "",
                     "photo": ({"card": ph["card"], "pos": (c.get("photo") or {}).get("pos", ""),
                                "fit": (c.get("photo") or {}).get("fit", "")} if ph else None)})
    os.makedirs("cars", exist_ok=True)
    with open(os.path.join("cars", "cars-data.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by cars_build.py from cars.js and articles.js. Don't edit this file: edit cars.js and run the build. */\n")
        f.write("const CARS_INDEX = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")

    # one page per car
    keep = set()
    for c in cars:
        folder = os.path.join("cars", c["id"])
        path = os.path.join(folder, "index.html")
        if os.path.exists(path) and MARK not in open(path, encoding="utf-8").read(3000):
            print(f"  skipped {path}: it wasn't made by cars_build.py")
            continue
        os.makedirs(folder, exist_ok=True)
        open(path, "w", encoding="utf-8").write(car_page(c, cars, by_id, arts, photos))
        keep.add(c["id"])
    removed = 0
    for name in os.listdir("cars"):
        p = os.path.join("cars", name, "index.html")
        if name not in keep and os.path.isfile(p) and MARK in open(p, encoding="utf-8").read(3000):
            shutil.rmtree(os.path.join("cars", name)); removed += 1

    # the plain list on /cars/
    idx = os.path.join("cars", "index.html")
    if os.path.exists(idx):
        page = open(idx, encoding="utf-8").read()
        if LIST_START in page and LIST_END in page:
            new = re.sub(re.escape(LIST_START) + r".*?" + re.escape(LIST_END),
                         lambda m: LIST_START + "\n" + static_list(cars) + "\n" + LIST_END, page, flags=re.S)
            if new != page:
                open(idx, "w", encoding="utf-8").write(new)

    if "--link-articles" in args:
        link_articles(cars, arts)

    no_photo = [c["id"] for c in cars if not photos[c["id"]]]
    print(f"\nCar pages built: {len(keep)}" + (f" (removed {removed} old ones)" if removed else ""))
    if no_photo:
        print("Still waiting for a photo: " + ", ".join(no_photo))
    print("Next: python3 seo_inject.py (adds the car pages to sitemap.xml)")


if __name__ == "__main__":
    main()
