def main():
    if not os.path.exists("events.js"):
        sys.exit("Run this from the top level of the repo (the folder holding events.js).")
    events, meets = read_events()
    items = []
    for e in events:
        if not e.get("start") or d(e.get("end") or e["start"]) < TODAY: continue
        items.append((e, "event", d(e["start"]) < TODAY))
    for m in meets: items.append((m, "meet", False))
    keep = set()
    for x, kind, ongoing in items:
        if not re.fullmatch(r"[a-z0-9-]{1,90}", x.get("id", "")): print("  skipped bad id:", x.get("id")); continue
        x["_when"] = x.get("schedule") if kind == "meet" else range_text(x)
    for x, kind, ongoing in items:
        pid = x.get("id", "")
        if not re.fullmatch(r"[a-z0-9-]{1,90}", pid): continue
        nearby = []
        if isinstance(x.get("lat"), (int, float)):
            for y, k2, _ in items:
                if y is x or not isinstance(y.get("lat"), (int, float)): continue
                mi = miles(x["lat"], x["lng"], y["lat"], y["lng"])
                if mi <= 60: nearby.append(dict(y, _mi=mi))
            nearby.sort(key=lambda n: n["_mi"]); nearby = nearby[:6]
        clean = {k: v for k, v in x.items() if not k.startswith("_")}
        out = page(clean, kind, ongoing, nearby)
        os.makedirs(os.path.join("events", pid), exist_ok=True)
        path = os.path.join("events", pid, "index.html")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if old != out: open(path, "w", encoding="utf-8").write(out)
        keep.add(pid)
    # state pages, plus Los Angeles & the South Bay
    by_state = {}
    for it in items:
        if re.fullmatch(r"[a-z0-9-]{1,90}", it[0].get("id", "")) and it[0].get("state") in STATES:
            by_state.setdefault(it[0]["state"], []).append(it)
    la = [it for it in items if it[0].get("region") == LA_REGION and re.fullmatch(r"[a-z0-9-]{1,90}", it[0].get("id", ""))]
    hubs = []
    if la: hubs.append((LA_HUB, LA_NAME, len(la)))
    hubs += [(slug(STATES[c]), STATES[c], len(v)) for c, v in sorted(by_state.items(), key=lambda kv: STATES[kv[0]])]
    clash = [h for h, n, c in hubs if h in keep]
    for h in clash: print("  skipped state page (a listing already uses that id):", h)
    hubs = [t for t in hubs if t[0] not in clash]
    for hslug, name, count in hubs:
        others = [t for t in hubs if t[0] != hslug]
        if hslug == LA_HUB:
            out = hub_page(hslug, name, la, [("California", hub_url("CA")), (name, f"/events/{hslug}/")], others,
                           "region=" + urllib.parse.quote_plus(LA_REGION))
        else:
            code = next(c for c in by_state if slug(STATES[c]) == hslug)
            extra = ""
            if code == "CA" and la:
                extra = f'<a class="lacall" href="/events/{LA_HUB}/">Los Angeles and the South Bay have their own page, with {len(la)} listings &rarr;</a>'
            out = hub_page(hslug, name, by_state[code], [(name, f"/events/{hslug}/")], others, "state=" + code, extra)
        os.makedirs(os.path.join("events", hslug), exist_ok=True)
        path = os.path.join("events", hslug, "index.html")
        old = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if old != out: open(path, "w", encoding="utf-8").write(out)
        keep.add(hslug)
    # the "Car events by state" links on the Events page
    ip = os.path.join("events", "index.html")
    if os.path.exists(ip):
        src = open(ip, encoding="utf-8").read()
        if LINKS_START in src and LINKS_END in src:
            new = re.sub(re.escape(LINKS_START) + r".*?" + re.escape(LINKS_END), lambda _m: links_block(hubs), src, count=1, flags=re.S)
            if new != src: open(ip, "w", encoding="utf-8").write(new)
    removed = 0
    for name in os.listdir("events"):
        p = os.path.join("events", name, "index.html")
        if name in keep or not os.path.isfile(p): continue
        if MARK in open(p, encoding="utf-8").read(2000):
            shutil.rmtree(os.path.join("events", name)); removed += 1
    print(f"event pages: {len(keep) - len(hubs)} current, {removed} removed (ended or no longer listed); state pages: {len(hubs)}")
    print("Next: python3 seo_inject.py (adds the event pages to sitemap.xml)")


if __name__ == "__main__":
    main()
