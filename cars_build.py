def split_name(name):
    """'Mazda RX-7 (FD)' -> ('Mazda RX-7', 'FD')"""
    m = re.match(r"^(.*?)\s*\(([^)]+)\)\s*$", name)
    return (m.group(1), m.group(2)) if m else (name, "")


def img_style(c):
    """object-position (pos) and object-fit (fit: "contain" shows the whole photo) for a car's photo"""
    p = c.get("photo") or {}
    s = (f'object-position:{p["pos"]};' if p.get("pos") else "") + ("object-fit:contain;" if p.get("fit") == "contain" else "")
    return f' style="{esc(s)}"' if s else ""


def credit_html(c):
    p = c.get("photo") or {}
    if not p:
        return ""
    if not p.get("file") and not p.get("page"):
        # your own photo in assets/images/cars/: no Wikimedia line, just the credit or caption if you gave one
        bits = [esc(p["caption"]) + "." if p.get("caption") else "", "Photo: " + esc(p["credit"]) if p.get("credit") else ""]
        bits = " ".join(b for b in bits if b)
        return f'<p class="credit">{bits}</p>' if bits else ""
    page = p.get("page") or ("https://commons.wikimedia.org/wiki/File:" + urllib.parse.quote(p["file"].replace(" ", "_")) if p.get("file") else "")
    lic = esc(p.get("license", ""))
    if p.get("licenseUrl"):
        lic = f'<a href="{esc(p["licenseUrl"])}" rel="license noopener" target="_blank">{lic}</a>'
    who = esc(p.get("credit", "")) or "Wikimedia Commons"
    where = f'<a href="{esc(page)}" rel="noopener" target="_blank">Wikimedia Commons</a>' if page else "Wikimedia Commons"
    shows = f'{esc(p["caption"])}. ' if p.get("caption") else ""
    return f'<p class="credit">{shows}Photo: {who} / {where}{", " + lic if lic else ""}</p>'


def json_ld(c, url, photo):
    o = {"@type": "Car", "@id": url + "#car", "name": c["name"], "url": url,
         "brand": {"@type": "Brand", "name": c["make"]},
         "manufacturer": {"@type": "Organization", "name": c.get("maker") or c["make"]},
         "description": c.get("quick", "")}
    if photo.get("safe"):
        o["image"] = photo["safe"] if photo["safe"].startswith("http") else SITE + photo["safe"]
    if c.get("start"):
        o["productionDate"] = str(c["start"])
    if c.get("body"):
        o["bodyType"] = c["body"]
    if c.get("engine"):
        o["vehicleEngine"] = {"@type": "EngineSpecification", "name": c["engine"]}
    crumbs = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "The Car Index", "item": SITE + "/cars/"},
        {"@type": "ListItem", "position": 2, "name": c["make"], "item": f"{SITE}/cars/?make={urllib.parse.quote(c['make'])}"},
        {"@type": "ListItem", "position": 3, "name": c["name"], "item": url}]}
    return json.dumps({"@context": "https://schema.org", "@graph": [o, crumbs]}, ensure_ascii=False).replace("</", "<\\/")


