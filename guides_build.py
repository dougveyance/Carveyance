def write(path, text):
    if os.path.exists(path):
        old = open(path, encoding="utf-8").read(3000)
        if MARK not in old:
            sys.exit(f"{path} wasn't made by guides_build.py, so it was left alone. Move it, then run this again.")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, "w", encoding="utf-8").write(text)


def made_by_us(folder):
    p = os.path.join(folder, "index.html")
