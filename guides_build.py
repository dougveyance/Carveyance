def chapter_page(g, c, cars):
    gurl = f"/fitdrive/guides/{g['id']}/"
    url = f"{SITE}{gurl}{c['slug']}/"
    body, cur, srcs, charts, heads = render_body(g, c["body"])
    mins = read_minutes(body, cur)
    c["_mins"] = mins
    img_url = f"{SITE}/fitdrive/guides/{g['id']}/img/{c.get('photo')}.jpg" if c.get("photo") and os.path.exists(photo_path(g, c["photo"])) else ""
    trail = [("Carveyance", "/"), ("FitDrive", "/fitdrive/"), ("Buyer's Guides", "/fitdrive/guides/"), (f"{g['make']} {g['model']}", gurl)]
    jump = ""
    if charts:
        seen, links = set(), []
        for k in charts:
            ch = g["charts"][k]
            if ch["n"] in seen:
                continue
            seen.add(ch["n"])
            links.append(f'<a href="#chart-{ch["n"]}">Chart {ch["n"]} &middot; {esc(ch["title"])}</a>')
        jump = f'<p class="gjump"><b>Charts in this chapter</b>{" ".join(links)}</p>'
    i = c["n"] - 1
    prev_c = g["chs"][i - 1] if i > 0 else None
    next_c = g["chs"][i + 1] if i + 1 < len(g["chs"]) else None
    pn = '<div class="gpn">'
