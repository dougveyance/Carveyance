def set_box(page_html, box):
    if BOX_START in page_html:
        return re.sub(re.escape(BOX_START) + r".*?" + re.escape(BOX_END) + r"\n*", lambda _m: (box + "\n\n") if box else "", page_html, flags=re.S)
    if not box: return page_html
    for marker in ("<!-- carveyance-subscribe -->", "</main>", "<footer", "</body>"):
        if marker in page_html:
            return page_html.replace(marker, box + "\n\n" + marker, 1)
    return page_html + box


