#!/usr/bin/env python3
"""
Carveyance — FitDrive Buyer's Guides
------------------------------------
Builds the buyer's guides from the files in guides_src/:

  guides_src/<guide>/guide.json   the guide's settings: byline, dates, the Car Index
                                  pages it belongs to, the chapter order, the charts
                                  and the photo list
  guides_src/<guide>/index.md     the guide's front page (carveyance.com/fitdrive/guides/<guide>/)
  guides_src/<guide>/NN-*.md      one file per chapter (carveyance.com/fitdrive/guides/<guide>/<slug>/)

and writes:

  fitdrive/guides/index.html                 the list of every guide
  fitdrive/guides/<guide>/index.html         each guide's front page
  fitdrive/guides/<guide>/<slug>/index.html  each chapter

Run it from the top level of the repo after changing anything in guides_src/,
then run cars_build.py (the Car Index pages link to the guides), seo_inject.py
(it adds the guide pages to sitemap.xml) and pwa_inject.py (it puts the home-screen
tags back on the Car Index pages):

    cd ~/GitHub/Carveyance
    python3 guides_build.py
    python3 cars_build.py
    python3 seo_inject.py
    python3 pwa_inject.py

FOR SALE: every guide page gets a "Find a <model> for sale" box after the chapter's
verdict (above The Carveyance Curiosity) and on the guide's front page, using the
everyday list in assets/js/cv-markets.js. In guide.json, "shop" can add the CarGurus
model code ("cargurus": "d290"), the model as the price sites spell it ("model"), or
"list": "collector" for a guide about collectible cars.

PHOTOS: save each photo as fitdrive/guides/<guide>/img/<slot>.jpg, where <slot> is
a name from the "photos" list in guide.json (for example ch1-hero.jpg), about 1600 px
wide. Add "credit" (and "caption" if you like) to that photo's entry in guide.json.
A chapter's main photo shows a "Photo coming soon" card until its file exists; the
photos inside a chapter ([[photo:...]]) only appear once their file exists.

WRITING A CHAPTER (plain text with a few marks):
  ---                       the settings block at the top: slug, nav (short name for the
  ...                       chapter list), title, seo (the title search engines show),
  ---                       kicker, dek, photo, stats ("270 hp = Power | 17 mpg = EPA ...")
  ## Heading                a section heading          ### Smaller heading
  - item                    a bulleted list            | a | b |   a table (first row = headings)
  **bold**  *italic*  [words](link)
  [[chart:torque]]          a chart from guide.json, numbered the same everywhere in the guide
  [[photo:ch1-cabin]]       a photo from the guide.json photo list
  ::: curiosity Title       The Carveyance Curiosity: write it after the verdict, close it
  ...                       with ::: on its own line. Leave it out when a car has nothing
  :::                       quirky enough; not every chapter needs one.
                            A [[photo:...]] line inside it puts a photo in the box.
  ## Sources                everything after this heading becomes the source list

It only writes pages that carry the "generated by guides_build.py" line, and it never
touches the img/ folders. Safe to run twice.
"""
