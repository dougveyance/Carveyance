def d(s): return datetime.date.fromisoformat(s)

MF = ["January","February","March","April","May","June","July","August","September","October","November","December"]
SEASON_RE = re.compile("(" + "|".join(MF) + r")\s*(?:–|—|-|through|to)\s*(" + "|".join(MF) + ")", re.I)

def season(s):
    m = SEASON_RE.search(s)
    if not m: return None
    low = [x.lower() for x in MF]
    return (low.index(m.group(1).lower()) + 1, low.index(m.group(2).lower()) + 1)   # months 1..12

def in_season(day, se):
    if not se: return True
    a, b = se
    return a <= day.month <= b if a <= b else (day.month >= a or day.month <= b)

def rule(m):
    """("weekly"|"monthly", weekday, ords, season) or None for irregular schedules
    ("Every other Sunday", "About 4 Saturdays a year", ...). Mirrors events-common.js."""
    s = m.get("schedule", "")
    wd = next((i for i, n in enumerate(WDF) if n in s), -1)
    if wd < 0: return None
    se = season(s)
    if not se and re.search(r"summer|spring|fall|autumn|winter|season|select|some ", s, re.I): return None   # vague: show the text only
    if re.match(r"Every " + WDF[wd] + r"\b", s): return ("weekly", wd, [], se)
    if not re.search(r"of the month", s, re.I): return None
    mp = {"1st":1, "2nd":2, "3rd":3, "4th":4, "last":-1}
    ords = [mp[o.lower()] for o in re.findall(r"1st|2nd|3rd|4th|Last", s, re.I)]
    return ("monthly", wd, ords, se) if ords else None

def nth_weekday(y, mo, wd, n):
    if n > 0:
        first = datetime.date(y, mo, 1)
        day = 1 + (wd - first.weekday()) % 7 + (n - 1) * 7
        try: return datetime.date(y, mo, day)
        except ValueError: return None
    nxt = datetime.date(y + (mo == 12), mo % 12 + 1, 1)
    last = nxt - datetime.timedelta(days=1)
    return last - datetime.timedelta(days=(last.weekday() - wd) % 7)

def occurrences(m, count=4):
    r = rule(m)
    if not r: return []
    kind, wd, ords, se = r
    out, day = [], TODAY
    if kind == "weekly":
        day += datetime.timedelta(days=(wd - day.weekday()) % 7)
        for _ in range(60):
            if in_season(day, se): out.append(day)
            if len(out) >= count: break
            day += datetime.timedelta(days=7)
        return out
    y, mo = TODAY.year, TODAY.month
    for _ in range(18):
        if in_season(datetime.date(y, mo, 1), se):
            out += sorted(x for x in (nth_weekday(y, mo, wd, o) for o in ords) if x and x >= TODAY)
        if len(out) >= count: break
        y, mo = (y + 1, 1) if mo == 12 else (y, mo + 1)
    return out[:count]

def parse_times(t):
    t = (t or "").lower()
    def h24(h, ap):
        h = int(h); ap = (ap or "")[:1]
        if ap == "p" and h < 12: h += 12
        if ap == "a" and h == 12: h = 0
        return h
    m = re.search(r"(\d{1,2})(?::(\d{2}))?\s*(am|pm|a\.m\.|p\.m\.)?\s*[–—-]\s*(\d{1,2})(?::(\d{2}))?\s*(am|pm|a\.m\.|p\.m\.)", t)
    if m:
        ap2 = m.group(6); ap1 = m.group(3) or ap2
        sh, eh = h24(m.group(1), ap1), h24(m.group(4), ap2)
        if not m.group(3) and sh > eh: sh = h24(m.group(1), "am" if ap2.startswith("p") else "pm")
        return (sh, int(m.group(2) or 0), eh, int(m.group(5) or 0))
    m = re.search(r"(\d{1,2})(?::(\d{2}))?\s*(am|pm|a\.m\.|p\.m\.)", t)
    if m:
        h = h24(m.group(1), m.group(3)); return (h, int(m.group(2) or 0), min(h + 2, 23), int(m.group(2) or 0))
    return None

def iso_at(day, h, mi, x):
    s = f"{day.isoformat()}T{h:02d}:{mi:02d}:00"
    try:
        from zoneinfo import ZoneInfo
        z = TZ_CITY.get((x.get("state"), x.get("city"))) or TZ_STATE.get(x.get("state"), "America/New_York")
        off = datetime.datetime(day.year, day.month, day.day, h, mi, tzinfo=ZoneInfo(z)).strftime("%z")
        return s + off[:3] + ":" + off[3:]
    except Exception:
        return s

