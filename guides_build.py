def esc(s, quote=True):
    return html.escape("" if s is None else str(s), quote=quote)


def nice_date(iso):
    d = datetime.date.fromisoformat(iso)
    return d.strftime("%B ") + str(d.day) + d.strftime(", %Y")


# ---------- reading the sources ----------
def split_front(text, path):
    if not text.startswith("---"):
        sys.exit(f"{path}: the settings block (between two --- lines) is missing at the top.")
    end = text.find("\n---", 3)
    if end < 0:
        sys.exit(f"{path}: the settings block isn't closed with a --- line.")
    meta = {}
    for line in text[3:end].strip().splitlines():
        if ":" in line:
            k, v = line.split(":", 1)
            meta[k.strip()] = v.strip()
    return meta, text[end + 4:].lstrip("\n")


def read_guide(folder):
    gid = os.path.basename(folder)
    try:
        g = json.load(open(os.path.join(folder, "guide.json"), encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as e:
        sys.exit(f"{folder}/guide.json: {e}")
    g["id"] = gid
    g["front"], g["front_body"] = split_front(open(os.path.join(folder, "index.md"), encoding="utf-8").read(), f"{folder}/index.md")
    chapters = {}
    for p in sorted(glob.glob(os.path.join(folder, "[0-9]*.md"))):
        meta, body = split_front(open(p, encoding="utf-8").read(), p)
        if not re.match(r"^[a-z0-9][a-z0-9-]*$", meta.get("slug", "")):
            sys.exit(f"{p}: the slug must be lowercase letters, numbers and hyphens.")
        meta["body"] = body
        chapters[meta["slug"]] = meta
    order = g.get("chapters") or list(chapters)
    missing = [s for s in order if s not in chapters]
    if missing:
        sys.exit(f"{folder}/guide.json lists chapters with no file: {', '.join(missing)}")
    g["chs"] = [chapters[s] for s in order]
    for i, c in enumerate(g["chs"]):
        c["n"] = i + 1
    return g


def read_car_index():
    """names and years of the Car Index pages, so a guide can link to them"""
    try:
        src = open("cars.js", encoding="utf-8").read()
        body = src[src.find("[", src.find("const CARS")):src.rfind("]") + 1]
        return {c["id"]: c for c in json.loads(re.sub(r",(\s*[\]}])", r"\1", body))}
    except Exception:
        return {}


# ---------- turning the text into HTML ----------
def inline(t):
    t = esc(t, quote=False)

    def link(m):
        words, url = m.group(1), m.group(2)
        ext = url.startswith("http")
        attr = ' target="_blank" rel="noopener"' if ext else ""
        return f'<a href="{url}"{attr}>{words}</a>'
    t = re.sub(r"\[([^\]]+)\]\(([^)\s]+)\)", link, t)
    t = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", t)
    t = re.sub(r"(?<![*\w])\*(?!\s)(.+?)(?<!\s)\*(?![*\w])", r"<em>\1</em>", t)
    return t


def slugify(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def photo_path(g, slot):
    return os.path.join(OUT, g["id"], "img", slot + ".jpg")


def photo_html(g, slot, hero=False):
    p = (g.get("photos") or {}).get(slot, {})
    if os.path.exists(photo_path(g, slot)):
        src = f"/fitdrive/guides/{g['id']}/img/{slot}.jpg"
        bits = [esc(p["caption"]) + "." if p.get("caption") else "", "Photo: " + esc(p["credit"]) if p.get("credit") else ""]
        cap = " ".join(b for b in bits if b)
        load = ' fetchpriority="high"' if hero else ' loading="lazy"'
        capx = "<figcaption>" + cap + "</figcaption>" if cap else ""
        alt = esc(p.get("alt", g["make"] + " " + g["model"]))
        return f'<figure class="{"ghero" if hero else "gfig"}"><img src="{src}" alt="{alt}"{load}>{capx}</figure>'
    if not hero:
        return ""
    return (f'<figure class="ghero"><div class="ph"><b>{esc(g["make"])} {esc(g["model"])}</b>'
            f'<span>Photo coming soon</span></div></figure>')


def chart_html(g, key):
    c = (g.get("charts") or {}).get(key)
    if not c:
        sys.exit(f"{g['id']}: [[chart:{key}]] isn't defined in guide.json")
    series = g.get("series") or {}
    top = max(b[1] for b in c["bars"])
    rows = ""
    for sid, val, label in c["bars"]:
        s = series.get(sid, {"name": sid, "color": "#2E6E96"})
        pct = max(2, round(val / top * 100, 1))
        rows += (f'<div class="bar" title="{esc(s["name"])}: {esc(label)}"><div class="bh"><span class="bn">{esc(s["name"])}</span>'
                 f'<b class="bv">{esc(label)}</b></div><div class="bt"><span class="bf" style="width:{pct}%;background:{esc(s["color"])}"></span></div></div>')
    n = c["n"]
    sub = '<p class="cs">' + inline(c["sub"]) + "</p>" if c.get("sub") else ""
    src = '<figcaption class="csrc">Source: ' + esc(c["source"]) + "</figcaption>" if c.get("source") else ""
    return (f'<figure class="chart" id="chart-{n}" aria-labelledby="chart-{n}-t"><div class="ck">Chart {n}</div>'
            f'<h3 class="ct" id="chart-{n}-t">{esc(c["title"])}</h3>{sub}<div class="bars">{rows}</div>{src}</figure>')


def table_html(rows):
    cells = [[x.strip() for x in r.strip().strip("|").split("|")] for r in rows]
    cells = [r for r in cells if not all(re.match(r"^:?-{2,}:?$", x) for x in r if x)]
    head, body = cells[0], cells[1:]
    th = "".join(f"<th scope=\"col\">{inline(x)}</th>" for x in head)
    lab = [re.sub(r"<[^>]+>", "", inline(x)) for x in head]
    tb = "".join("<tr>" + "".join((f'<th scope="row">{inline(x)}</th>' if i == 0 else
                                   f'<td data-label="{lab[i] if i < len(lab) else ""}">{inline(x)}</td>') for i, x in enumerate(r)) + "</tr>" for r in body)
    return f'<div class="gtable"><table><thead><tr>{th}</tr></thead><tbody>{tb}</tbody></table></div>'


def curiosity_html(title, lines, g=None):
    out, para, sw = [], [], None
    for ln in lines + [""]:
        s = ln.strip()
        m = re.match(r"^\[\[photo:([a-z0-9-]+)\]\]$", s)
        if m and g is not None:
            if para:
                out.append(f"<p>{inline(' '.join(para))}</p>")
                para = []
            out.append(photo_html(g, m.group(1)))
            continue
        if s == "[[swatches]]":
            if para:
                out.append(f"<p>{inline(' '.join(para))}</p>")
                para = []
            sw = []
            continue
        if s == "[[/swatches]]":
            chips = "".join(f'<li><i style="background:{esc(c)}"></i><b>{esc(y)}</b><span>{esc(nm)}</span></li>' for y, nm, c in sw)
            out.append(f'<ul class="swatches">{chips}</ul>')
            sw = None
            continue
        if sw is not None:
            parts = [p.strip() for p in s.split("=")]
            if len(parts) == 3:
                sw.append(parts)
            continue
        if not s:
            if para:
                out.append(f"<p>{inline(' '.join(para))}</p>")
                para = []
            continue
        para.append(s)
    return (f'<aside class="curio" aria-label="The Carveyance Curiosity"><div class="cmark"><span>The Carveyance</span>Curiosity</div>'
            f'<h2 class="ctitle">{inline(title)}</h2>{"".join(out)}</aside>')


def render_body(g, text):
    """returns (body_html, curiosity_html, sources_html, charts_used, headings)"""
    out, cur, srcs, charts, heads = [], "", [], [], []
    para, items, rows = [], [], []
    in_sources = False
    lines = text.splitlines()

    def flush():
        nonlocal para, items, rows
        if para:
            out.append(f"<p>{inline(' '.join(para))}</p>")
        if items:
            out.append("<ul>" + "".join(f"<li>{inline(x)}</li>" for x in items) + "</ul>")
        if rows:
            out.append(table_html(rows))
        para, items, rows = [], [], []

    i = 0
    while i < len(lines):
        s = lines[i].strip()
        i += 1
        if in_sources:
            if s.startswith("- "):
                srcs.append(inline(s[2:]))
            continue
        if not s:
            flush()
            continue
        if s.startswith("::: curiosity"):
            flush()
            title, body = s[len("::: curiosity"):].strip(), []
            while i < len(lines) and lines[i].strip() != ":::":
                body.append(lines[i])
                i += 1
            i += 1
            cur = curiosity_html(title, body, g)
            continue
        if s.startswith("## "):
            flush()
            h = s[3:].strip()
            if h.lower() == "sources":
                in_sources = True
                continue
            hid = slugify(h)
            heads.append((hid, h))
            out.append(f'<h2 id="{hid}">{inline(h)}</h2>')
            continue
        if s.startswith("### "):
            flush()
            out.append(f"<h3>{inline(s[4:])}</h3>")
            continue
        m = re.match(r"^\[\[chart:([a-z0-9-]+)\]\]$", s)
        if m:
            flush()
            out.append(chart_html(g, m.group(1)))
            charts.append(m.group(1))
            continue
        m = re.match(r"^\[\[photo:([a-z0-9-]+)\]\]$", s)
        if m:
            flush()
            out.append(photo_html(g, m.group(1)))
            continue
        if s.startswith("- "):
            if para or rows:
                flush()
            items.append(s[2:])
            continue
        if s.startswith("|"):
            if para or items:
                flush()
            rows.append(s)
            continue
        if items or rows:
            flush()
        para.append(s)
    flush()
    src_html = ("<section class=\"gsources\"><h2>Sources</h2><ul>" + "".join(f"<li>{x}</li>" for x in srcs) + "</ul></section>") if srcs else ""
    return "\n".join(out), cur, src_html, charts, heads


def read_minutes(*parts):
    words = len(re.sub(r"<[^>]+>", " ", " ".join(parts)).split())
    return max(1, math.ceil(words / 230))


