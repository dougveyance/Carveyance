# ---------- reading the data ----------
def read_owners(path="owners.js"):
    if not os.path.exists(path): return []
    src = open(path, encoding="utf-8").read()
    i = src.find("const OWNERS")
    if i < 0: return []
    body = src[src.index("[", i):]
    depth, end = 0, None
    for k, ch in enumerate(body):
        if ch == "[": depth += 1
        elif ch == "]":
            depth -= 1
            if depth == 0: end = k; break
    body = body[:end + 1]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"(?m)^\s*//.*$", "", body)
    body = re.sub(r",(\s*[\]}])", r"\1", body)                 # tolerate trailing commas
    try:
        owners = json.loads(body)
    except json.JSONDecodeError as e:
        sys.exit(f"owners.js has a typo near line {body[:e.pos].count(chr(10)) + 1} of the list: {e.msg}. "
                 "Check the quotes and commas.")
    out = []
    for o in owners:
        if not re.fullmatch(r"[a-z0-9-]{1,60}", str(o.get("id", ""))):
            print("  skipped owner with a bad id:", o.get("id")); continue
        o.setdefault("cars", [])
        out.append(o)
    return out

def read_articles(path="articles.js"):
    src = open(path, encoding="utf-8").read()
    body = src[src.find("const ARTICLES"):]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    out = []
    for m in re.finditer(r"\{(.*?)\n  \}", body, re.S):
        blk = m.group(1)
        def g(key):
            hit = re.search(r'"?%s"?\s*:\s*"((?:[^"\\]|\\.)*)"' % key, blk)
            if not hit: return ""
            raw = hit.group(1)
            try: raw = json.loads('"' + raw + '"')          # \u2014 and friends
            except ValueError: pass
            return html.unescape(raw)                         # &mdash; and friends
        if g("slug"):
            out.append({k: g(k) for k in ("slug", "title", "subtitle", "category", "date", "readTime", "blurb", "image", "owner", "ownerCar")})
    return out


# ---------- helpers ----------
def esc(s): return html.escape(str(s or ""), quote=True)
def first_name(o): return re.split(r"[ .]", o["name"].strip())[0] or o["name"]
def ig_url(h):
    h = (h or "").strip().lstrip("@")
    return f"https://www.instagram.com/{h}/" if re.fullmatch(r"[A-Za-z0-9._]{1,30}", h) else ""
def safe_img(u):
    u = (u or "").strip()
    return u if re.fullmatch(r"(/|https://)[^\"'<>\s]+\.(jpe?g|png|webp)", u, re.I) else ""
def monogram(o):
    parts = [p for p in re.split(r"\s+", o["name"].replace(".", " ")) if p]
    return esc("".join(p[0] for p in parts[:2]).upper())
def plural(n, word):
    many = {"story": "stories"}.get(word, word + "s")
    return f"{n} {word if n == 1 else many}"
def fmt_date(iso):
    try:
        d = datetime.date.fromisoformat(iso); return d.strftime("%B ") + str(d.day) + d.strftime(", %Y")
    except ValueError: return iso

def site_parts():
    """the nav and footer, copied from the section page so they always match the rest of the site"""
    p = SECTION_URL.strip("/") + "/index.html"
    src = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
    nav = re.search(r"<nav>.*?</nav>", src, re.S)
    foot = re.search(r"<footer>.*?</footer>", src, re.S)
    return (nav.group(0) if nav else ""), (foot.group(0) if foot else "")

