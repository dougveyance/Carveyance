def an(word):
    """'a' or 'an' before a model name: an Avalon, an RX-7, a 4Runner, an 86"""
    w = str(word).strip()
    return "an" if re.match(r"(?i)([aeio]|8|11\b|18\b|rx|sl|sx|f-|x[0-9 ]|hr|mr|s[0-9]|e-|l[0-9]|m[0-9])", w) else "a"


