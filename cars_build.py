def read_cars(path="cars.js"):
    src = open(path, encoding="utf-8").read()
    start = src.find("[", src.find("const CARS"))
    end = src.rfind("]")
    if start < 0 or end < 0:
        sys.exit("cars.js: couldn't find the list of cars (const CARS = [ ... ];)")
    body = src[start:end + 1]
    body = re.sub(r",(\s*[\]}])", r"\1", body)          # forgive a trailing comma
    try:
        cars = json.loads(body)
    except json.JSONDecodeError as e:
        line = body[:e.pos].count("\n") + src[:start].count("\n") + 1
        sys.exit(f"cars.js has a typo near line {line}: {e.msg}. Check the quotes and commas there.")
    ids = set()
    for c in cars:
        if not re.match(r"^[a-z0-9][a-z0-9-]{1,79}$", c.get("id", "")):
            sys.exit(f"cars.js: '{c.get('id')}' isn't a valid id (lowercase letters, numbers and hyphens).")
        if c["id"] in ids:
            sys.exit(f"cars.js: the id '{c['id']}' is used twice.")
        ids.add(c["id"])
    return cars


def read_articles(path="articles.js"):
    src = open(path, encoding="utf-8").read()
    body = src[src.find("const ARTICLES"):]
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    out = {}
    for m in re.finditer(r"\{(.*?)\n  \}", body, re.S):
        blk = m.group(1)
        def g(key):
            hit = re.search(r'"?%s"?\s*:\s*"((?:[^"\\]|\\.)*)"' % key, blk)
            if not hit:
                return ""
            try:
                return json.loads('"' + hit.group(1) + '"')     # turns \u00eb and \" back into text
            except ValueError:
                return hit.group(1).replace('\\"', '"')
        slug = g("slug")
        if not slug:
            continue
        veh = re.search(r'"?vehicles"?\s*:\s*\[(.*?)\]', blk, re.S)
        out[slug] = {k: g(k) for k in ("slug", "title", "subtitle", "category", "date", "readTime", "image")}
        vs = re.findall(r'"((?:[^"\\]|\\.)*)"', veh.group(1)) if veh else []
        out[slug]["vehicles"] = [json.loads('"' + v + '"') if "\\" in v else v for v in vs]
    return out


