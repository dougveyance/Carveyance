def num(n):
    return f"{n:,}"


def lb(kg):
    return int(round(kg * 2.20462))


def stat_blocks(c):
    out = []
    p = c.get("power") or {}
    out.append(("Power", (num(int(round(p["hp"]))), "hp") if p.get("hp") else None, p.get("note", "")))
    w = c.get("weight") or {}
    out.append(("Weight", (num(int(round(w["kg"]))), "kg") if w.get("kg") else None,
                (f"{num(lb(w['kg']))} lb" + (" &middot; " + esc(w["note"]) if w.get("note") else "")) if w.get("kg") else ""))
    z = c.get("zero60") or {}
    zs = ""
    if z.get("sec"):
        zs = z.get("note") or ("Maker's claim" if z.get("kind") == "claimed" else "Road test")
    out.append(("0-60 mph", (f"{float(z['sec']):.1f}", "sec") if z.get("sec") else None, zs))
    t = c.get("top") or {}
    ts = ""
    if t.get("mph"):
        ts = t.get("note") or ("Maker's claim" if t.get("kind") == "claimed" else "Tested")
    out.append(("Top speed", (num(int(round(t["mph"]))), "mph") if t.get("mph") else None, ts))
    b = c.get("built") or {}
    out.append(("Built", (("about " if b.get("approx") else "") + num(int(b["count"])), "") if b.get("count") else None, b.get("note", "")))
    return out


def src_label(s, arts):
    if not s:
        return None
    if s.startswith("article:"):
        a = arts.get(s[8:])
        return (f"/articles/{s[8:]}/", f"Carveyance: {a['title']}" if a else "Carveyance") if a else None
    if s.startswith("http"):
        host = urllib.parse.urlparse(s).netloc.replace("www.", "")
        return (s, host)
    return None


