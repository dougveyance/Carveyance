def parse_obj(line):
    """one `{key:value, ...}` line of events.js -> dict (values are JSON)"""
    s = line.strip().rstrip(",")
    dec, out, i = json.JSONDecoder(), {}, 1
    while True:
        while s[i] in " ,": i += 1
        if s[i] == "}": return out
        j = s.index(":", i)
        key = s[i:j].strip()
        val, i = dec.raw_decode(s, j + 1)
        out[key] = val

def read_events(path="events.js"):
    src = open(path, encoding="utf-8").read()
    lists, cur = {"EVENTS": [], "MEETS": []}, None
    for line in src.splitlines():
        m = re.match(r"\s*const\s+(EVENTS|MEETS)\s*=", line)
        if m: cur = m.group(1); continue
        if cur and re.match(r"\s*\{id:", line):
            lists[cur].append(parse_obj(line))
        elif cur and line.strip().startswith("];"):
            cur = None
    return lists["EVENTS"], lists["MEETS"]


