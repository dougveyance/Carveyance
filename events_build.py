def miles(a, b, c, e):
    import math
    r = math.pi / 180
    h = math.sin((c - a) * r / 2) ** 2 + math.cos(a * r) * math.cos(c * r) * math.sin((e - b) * r / 2) ** 2
    return 2 * 3958.8 * math.asin(math.sqrt(h))

def json_ld(x, kind, page):
    place = {"@type": "Place", "name": x.get("venue") or x.get("city") or "",
             "address": {"@type": "PostalAddress", "addressLocality": x.get("city", ""),
                         "addressRegion": x.get("state", ""), "addressCountry": "US"}}
    if x.get("address"): place["address"]["streetAddress"] = x["address"]
    if isinstance(x.get("lat"), (int, float)): place["geo"] = {"@type": "GeoCoordinates", "latitude": x["lat"], "longitude": x["lng"]}
    base = {"@type": "Event", "name": x["name"], "description": x.get("blurb", ""), "url": page,
            "eventAttendanceMode": "https://schema.org/OfflineEventAttendanceMode",
            "eventStatus": "https://schema.org/" + STATUS.get(x.get("status"), ("", "EventScheduled"))[1],
            "location": place}
    if x.get("url") and not x.get("via"): base["organizer"] = {"@type": "Organization", "name": x["name"], "url": x["url"]}
    if x.get("image"): base["image"] = [SITE + x["image"] if x["image"].startswith("/") else x["image"]]
    if re.match(r"\s*free\b", x.get("cost", ""), re.I):
        base["offers"] = {"@type": "Offer", "price": 0, "priceCurrency": "USD", "availability": "https://schema.org/InStock", "url": x.get("url") or page}
    tm = parse_times(x.get("time"))
    out = []
    if kind == "meet":
        for day in occurrences(x):
            ev = dict(base)
            if tm: ev["startDate"], ev["endDate"] = iso_at(day, tm[0], tm[1], x), iso_at(day, tm[2], tm[3], x)
            else: ev["startDate"] = day.isoformat()
            out.append(ev)
    else:
        ev = dict(base); s, en = d(x["start"]), d(x.get("end") or x["start"])
        if tm and s == en: ev["startDate"], ev["endDate"] = iso_at(s, tm[0], tm[1], x), iso_at(s, tm[2], tm[3], x)
        else: ev["startDate"], ev["endDate"] = s.isoformat(), en.isoformat()
        out.append(ev)
    crumbs = {"@type": "BreadcrumbList", "itemListElement": [
        {"@type": "ListItem", "position": 1, "name": "Events", "item": SITE + "/events/"},
        {"@type": "ListItem", "position": 2, "name": STATES.get(x.get("state"), x.get("state", "")), "item": SITE + hub_url(x.get("state"))},
        {"@type": "ListItem", "position": 3, "name": x["name"], "item": page}]}
    return json.dumps({"@context": "https://schema.org", "@graph": out + [crumbs]}, ensure_ascii=False).replace("</", "<\\/")

